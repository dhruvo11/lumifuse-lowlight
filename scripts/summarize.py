"""Aggregate results/raw/*.json into markdown tables (results/summary.md + summary.json).
Every number in the README / design doc / eval file / report comes from here."""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
import numpy as np  # noqa: E402

from scripts.evaluate import ABLATION, CLASSICAL_ABL, MAIN, load_sets, slug  # noqa: E402

RAW = os.path.join(ROOT, "results", "raw")
COLS = [("psnr", "PSNR (dB) ↑", 2), ("ssim", "SSIM ↑", 4), ("lpips", "LPIPS ↓", 4), ("niqe", "NIQE ↓", 3),
        ("ms", "Latency (ms) ↓", 0), ("noise", "Noise σ ↓", 4), ("edge", "Edge corr. ↑", 4)]


def load(sname, tag, vname):
    p = os.path.join(RAW, f"{slug(sname)}__{slug(tag + '_' + vname)}.json")
    return json.load(open(p)) if os.path.exists(p) else None


def agg(rows):
    out = {}
    for k, _, _ in COLS:
        vals = [r[k] for r in rows if k in r and r[k] is not None and np.isfinite(r[k])]
        out[k] = float(np.mean(vals)) if vals else None
    out["n"] = len(rows)
    return out


def table(sname, tag, variants, latency=None, bold_best=True):
    res = {v: load(sname, tag, v) for v in variants}
    res = {v: agg(r) for v, r in res.items() if r}
    if not res:
        return "", {}
    if latency:  # replace throughput timings with the controlled CPU benchmark
        for v in res:
            if v in latency:
                res[v]["ms"] = latency[v]["mean_ms"]
    cols = [c for c in COLS if any(res[v].get(c[0]) is not None for v in res)]
    best = {}
    for k, _, _ in cols:
        vals = {v: res[v][k] for v in res if res[v][k] is not None}
        if vals and k != "ms":
            best[k] = (max if k in ("psnr", "ssim", "edge") else min)(vals, key=vals.get)
    lines = ["| Method | " + " | ".join(c[1] for c in cols) + " |", "|---|" + "---:|" * len(cols)]
    for v in res:
        cells = []
        for k, _, d in cols:
            x = res[v][k]
            s = "—" if x is None else f"{x:.{d}f}"
            if bold_best and best.get(k) == v:
                s = f"**{s}**"
            cells.append(s)
        lines.append(f"| {v} | " + " | ".join(cells) + " |")
    return "\n".join(lines), res


def main():
    sets = load_sets()
    lat_path = os.path.join(ROOT, "results", "latency.json")
    latency = json.load(open(lat_path))["results"] if os.path.exists(lat_path) else None
    md, js = ["# Results summary (auto-generated by scripts/summarize.py)\n"], {}
    if latency:
        md.append("Latency column: CPU benchmark (Apple M1, 4 threads, 600×400, mean of 15 LOL images) for the four "
                  "main methods; ablation rows show wall-clock time of the evaluation run (MPS).\n")
    for sname, items in sets.items():
        t, r = table(sname, "main", MAIN, latency)
        if t:
            md += [f"## {sname} (n={len(items)})\n", t, ""]
            js[f"main/{sname}"] = r
    for sname in ("LOL-v1 eval15", "LOL-v2-real test (unseen)", "Synthetic extreme-dark", "Synthetic non-uniform"):
        t, r = table(sname, "abl", ABLATION)
        if t:
            md += [f"## Ablation — hybrid — {sname}\n", t, ""]
            js[f"abl/{sname}"] = r
    for sname in ("LOL-v1 eval15", "LOL-v2-real test (unseen)", "Synthetic extreme-dark", "Synthetic non-uniform"):
        t, r = table(sname, "cabl", CLASSICAL_ABL)
        if t:
            md += [f"## Ablation — classical — {sname}\n", t, ""]
            js[f"cabl/{sname}"] = r
    open(os.path.join(ROOT, "results", "summary.md"), "w").write("\n".join(md))
    json.dump(js, open(os.path.join(ROOT, "results", "summary.json"), "w"), indent=1)
    print("\n".join(md))


if __name__ == "__main__":
    main()
